#!/usr/bin/env node
/* Writes packages/ui/src/lib/tailscale-roots.ts: the root certificates Tailscale's WebAssembly client verifies TLS with.
   The Go runtime in a browser has no system certificate store, so without these every HTTPS fetch through the tailnet
   fails with "x509: certificate signed by unknown authority". They are Node's bundled roots (`tls.rootCertificates`),
   which are Mozilla's CA store (NSS, MPL-2.0); rerun with a newer Node to refresh them.

     node tools/tailscale/roots.mjs            → write the module
     node tools/tailscale/roots.mjs --check    → exit 1 if it would change */
import { readFileSync, writeFileSync } from 'node:fs';
import { rootCertificates } from 'node:tls';

const OUT = new URL('../../packages/ui/src/lib/tailscale-roots.ts', import.meta.url);
const pem = rootCertificates.join('\n') + '\n';
const body = `/* Generated by tools/tailscale/roots.mjs — do not edit. ${rootCertificates.length} root certificates from Node ${process.versions.node}'s
   tls.rootCertificates (Mozilla's CA store, MPL-2.0), as one PEM bundle for Tailscale's WebAssembly client (see
   createTailscaleConnectClient's \`caCertificates\`). Imported lazily: it loads with the client, not with the page. */
const TAILSCALE_ROOT_CERTIFICATES = ${JSON.stringify(pem)};
export default TAILSCALE_ROOT_CERTIFICATES;
`;
if (process.argv.includes('--check')) {
  // Only the certificates matter: a different Node version in the header is not a change.
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  const certs = (s) => s.slice(s.indexOf('const TAILSCALE_ROOT_CERTIFICATES'));
  if (certs(current) !== certs(body)) { console.error('tailscale-roots: out of date — run node tools/tailscale/roots.mjs'); process.exit(1); }
  console.log(`tailscale-roots: ${rootCertificates.length} certificates; up to date`);
} else {
  writeFileSync(OUT, body);
  console.log(`tailscale-roots: wrote ${rootCertificates.length} certificates`);
}
